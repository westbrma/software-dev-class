// strings are text values, they can be characters, numbers, symbols, words, paragraphcs
// they must be inside of quotes so the computer knows its a string and not syntax
const greeting = 'Hello World!';

// strings can be combined
const user_name = 'Mark';

alert(greeting + ': ' + user_name);

// or like this using `` (backticks)
alert(`${greeting}: ${user_name}`);

// strings can be combined with numbers as well
