// inside () are the arguments or parameters of the function (inputs)
// inside { } is the body, a function can return a value but does not have to
function add_two_numbers(number_1, number_2) {
	return number_1 + number_2;
}

//  "arrow" or "lambda" function style
const add_two_number = (number_1, number_2) => {
	return number_1 + number_2;
};
